// Builds the blur-up placeholders: a 16px-wide webp of every gallery render
// (the poster frame for films), base64-encoded into src/data/galleryBlur.js
// and keyed by the same base path galleryData uses. src/lib/blur.js wraps
// each one in an SVG blur and paints it behind the image while it loads.
//
//   node scripts/media/build-blur-placeholders.mjs
//
// Reads the local copy of the deploy media (~/Documents/SKLO-media-masters/
// deploy, or MEDIA_LOCAL_ROOT) and falls back to the -640 variant on
// media.sklo.studio. Re-run after adding renders to galleryData.
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import sharp from "sharp";
import { galleryItems, virtualStagingPairs } from "../../src/data/galleryData.js";

const LOCAL = process.env.MEDIA_LOCAL_ROOT || path.join(os.homedir(), "Documents/SKLO-media-masters/deploy");
const REMOTE = "https://media.sklo.studio";
const WIDTH = 16;

const sources = new Set();
for (const item of galleryItems) if (item.src?.startsWith("/assets/gallery/")) sources.add(item.src);
for (const pair of virtualStagingPairs ?? []) for (const s of [pair.before, pair.after]) if (s) sources.add(s);

// The file the placeholder is cut from: the smallest image variant, or the
// poster frame for a film.
const sourceFor = (src) =>
  /\.(mp4|webm)$/i.test(src) ? src.replace(/\.(mp4|webm)$/i, "-poster.webp") : src.replace(/\.(webp|jpe?g|png)$/i, "-640.webp");

async function read(file) {
  const local = path.join(LOCAL, file.replace(/^\/assets\//, ""));
  if (fs.existsSync(local)) return fs.readFileSync(local);
  const res = await fetch(REMOTE + file);
  if (!res.ok) throw new Error(`${res.status} ${file}`);
  return Buffer.from(await res.arrayBuffer());
}

const out = {};
let failed = 0;
for (const src of [...sources].sort()) {
  try {
    const buf = await sharp(await read(sourceFor(src))).resize(WIDTH).webp({ quality: 50 }).toBuffer();
    out[src] = buf.toString("base64");
  } catch (e) {
    failed++;
    console.error("skip", src, e.message);
  }
}

const body = `// Generated by scripts/media/build-blur-placeholders.mjs — do not edit.
// ${Object.keys(out).length} blur-up placeholders (${WIDTH}px webp, base64), keyed by gallery path.
// Imported only by the components that show gallery media, never by the
// header or the home page, so it stays out of every other route's bundle.
const galleryBlur = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};
export default galleryBlur;
`;
fs.writeFileSync("src/data/galleryBlur.js", body);
console.log(`placeholders: ${Object.keys(out).length}, failed: ${failed}, ${(Buffer.byteLength(body) / 1024).toFixed(1)} KB`);
