"""Build src/data/regionMaps.js: a tiny equirectangular world map as SVG
path data, plus one path per SKLO market, for the "where we work" rows.

Source: Natural Earth 1:110m admin-0 countries (public domain),
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson

    python3 scripts/maps/build_region_maps.py path/to/ne_110m_admin_0_countries.geojson

The map is 96 x 44 units (Antarctica dropped, latitudes 82..-56). Points
are rounded to 0.05 and lightly thinned: the rows zoom in on their market.
"""
import json, sys

W, H, LAT0, LAT1 = 96.0, 44.0, 82.0, -56.0

REGIONS = {
    "europe": lambda p: p["CONTINENT"] == "Europe" and p["ISO_A2_EH"] != "RU",
    "north-america": lambda p: p["ISO_A2_EH"] in ("US", "CA"),
    "middle-east": lambda p: p["SUBREGION"] == "Western Asia" and p["ISO_A2_EH"] not in ("GE", "AM", "AZ", "CY"),
    "oceania": lambda p: p["ISO_A2_EH"] in ("AU", "NZ", "PG"),
    "latin-america": lambda p: p["SUBREGION"] in ("South America", "Central America", "Caribbean") or p["ISO_A2_EH"] == "MX",
}


def proj(lon, lat):
    return (lon + 180) / 360 * W, (LAT0 - lat) / (LAT0 - LAT1) * H


def ring_path(ring):
    pts, last = [], None
    for lon, lat in ring:
        x, y = proj(lon, lat)
        x, y = round(x * 20) / 20, round(y * 20) / 20
        if last and abs(x - last[0]) + abs(y - last[1]) < 0.2:
            continue
        pts.append((x, y))
        last = (x, y)
    if len(pts) < 3:
        return ""
    fmt = lambda v: ("%g" % v)
    return "M" + "L".join(f"{fmt(x)} {fmt(y)}" for x, y in pts) + "Z"


def feature_path(geom):
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    return "".join(ring_path(poly[0]) for poly in polys)


# Each row's map is zoomed onto its market: a box around the market's
# mainland, padded so some neighbouring land stays for orientation, widened
# to the icon's aspect. Hand-set extents (lon/lat) rather than the bbox of
# every island — French Guiana, Hawaii or the Aleutians would zoom it out.
FOCUS = {
    "europe": (-12, 72, 35, 34),
    "north-america": (-130, 60, -60, 22),
    "middle-east": (25, 42, 63, 11),
    "oceania": (110, -6, 180, -48),
    "latin-america": (-118, 30, -32, -56),
}
ASPECT = 1.6  # width / height of the rendered icon


def view_box(slug):
    lon0, lat0, lon1, lat1 = FOCUS[slug]
    x0, y0 = proj(lon0, lat0)
    x1, y1 = proj(lon1, lat1)
    w, h = x1 - x0, y1 - y0
    pad = 0.12
    x0, y0, w, h = x0 - w * pad, y0 - h * pad, w * (1 + 2 * pad), h * (1 + 2 * pad)
    if w / h < ASPECT:
        nw = h * ASPECT
        x0 -= (nw - w) / 2
        w = nw
    else:
        nh = w / ASPECT
        y0 -= (nh - h) / 2
        h = nh
    return f"{x0:.1f} {y0:.1f} {w:.1f} {h:.1f}"


def main(src):
    data = json.load(open(src))
    world, regions = [], {k: [] for k in REGIONS}
    for ft in data["features"]:
        p = ft["properties"]
        if p["CONTINENT"] == "Antarctica":
            continue
        d = feature_path(ft["geometry"])
        hit = next((k for k, f in REGIONS.items() if f(p)), None)
        (regions[hit] if hit else world).append(d)
    out = [
        "// GENERATED by scripts/maps/build_region_maps.py — do not edit by hand.",
        "// Natural Earth 1:110m admin-0 countries (public domain), equirectangular,",
        "// 96 x 44 units. WORLD is every country outside the five markets; each",
        "// REGION path is that market's countries.",
        "",
        f'export const WORLD = "{"".join(world)}";',
        "",
        "export const REGIONS = {",
    ]
    out += [f'  "{k}": "{"".join(v)}",' for k, v in regions.items()]
    out += ["};", "", "// viewBox per market, zoomed onto it (see FOCUS in the script).", "export const VIEWBOX = {"]
    out += [f'  "{k}": "{view_box(k)}",' for k in REGIONS]
    out += ["};", ""]
    open("src/data/regionMaps.js", "w").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
